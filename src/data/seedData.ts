export function buildInitialInvoices(): Invoice[] {
  const built: Invoice[] = [];

  for (const bp of BLUEPRINTS) {
    const customer = INITIAL_CUSTOMERS.find((c) => c.id === bp.customerId)!;
    const lineInputs: InvoiceLineInput[] = bp.lines.map((l) => {
      const prod = INITIAL_PRODUCTS.find((p) => p.id === l.productId)!;
      return {
        productId: prod.id,
        productName: prod.name,
        hsnCode: prod.hsnCode,
        category: prod.category,
        unit: prod.unit,
        quantity: l.quantity,
        unitPrice: l.overridePrice ?? prod.unitPrice,
        discountPercent: l.discountPercent,
        gstRate: l.overrideGstRate ?? prod.gstRate,
      };
    });

    const totals = calculateInvoiceTotals(
      lineInputs,
      DEFAULT_SELLER_PROFILE.state,
      customer.state
    );

    const anomalies = detectInvoiceAnomalies(
      {
        invoiceId: bp.id,
        issueDate: bp.issueDate,
        customerId: customer.id,
        customerName: customer.businessName || customer.name,
        items: totals.items,
        grandTotal: totals.grandTotal,
      },
      built,
      INITIAL_PRODUCTS
    );

    const amountPaid = Math.round(totals.grandTotal * bp.amountPaidRatio);

    built.push({
      id: bp.id,
      invoiceNumber: bp.invoiceNumber,
      issueDate: bp.issueDate,
      dueDate: bp.dueDate,
      customerId: customer.id,
      customerName: customer.businessName || customer.name,
      customerGstin: customer.gstin,
      customerState: customer.state,
      customerAddress: `${customer.address}, ${customer.city} - ${customer.pincode}`,
      supplyType: totals.supplyType,
      items: totals.items,
      subtotal: totals.subtotal,
      totalDiscount: totals.totalDiscount,
      taxableAmount: totals.taxableAmount,
      cgstTotal: totals.cgstTotal,
      sgstTotal: totals.sgstTotal,
      igstTotal: totals.igstTotal,
      totalTax: totals.totalTax,
      roundOff: totals.roundOff,
      grandTotal: totals.grandTotal,
      amountPaid,
      paymentStatus: bp.paymentStatus,
      notes: bp.notes,
      anomalies,
      hasUnreviewedAnomalies: anomalies.some((a) => !a.reviewed),
      injectedAnomalyGroundTruth: bp.injectedAnomalyGroundTruth,
      createdAt: `${bp.issueDate}T10:30:00Z`,
    });
  }

  return built;
}

